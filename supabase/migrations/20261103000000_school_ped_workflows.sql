-- School PeD: a school's outgoing letter is the assigned office's incoming
-- school letter. The school's own incoming register remains private to it.
begin;

alter table public.profiles drop constraint if exists profiles_ped_office_school_only;
alter table public.profiles
  add column if not exists ped_office_id uuid references public.profiles(id) on delete set null;

alter table public.profiles
  add constraint profiles_ped_office_school_only check (
    ped_office_id is null or
    (role = 'agency' and lower(btrim(agency_type)) = 'sekolah')
  );

alter table public.ped_correspondence
  add column if not exists school_id uuid references public.profiles(id) on delete restrict,
  add column if not exists office_id uuid references public.profiles(id) on delete restrict;

alter table public.ped_correspondence
  drop constraint if exists ped_correspondence_category_check,
  drop constraint if exists ped_correspondence_category_required_fields;

-- PostgreSQL gives inline check constraints autogenerated names.
do $$
declare old_check text;
begin
  select conname into old_check
    from pg_constraint
   where conrelid = 'public.ped_correspondence'::regclass
     and contype = 'c'
     and pg_get_constraintdef(oid) like '%agency_in%school_in%outgoing%';
  if old_check is not null then
    execute format('alter table public.ped_correspondence drop constraint %I', old_check);
  end if;
end;
$$;

alter table public.ped_correspondence
  add constraint ped_correspondence_category_check
    check (category in ('agency_in', 'school_in', 'outgoing', 'school_received')),
  add constraint ped_correspondence_category_required_fields check (
    btrim(subject) <> '' and
    case category
      when 'agency_in' then btrim(sender) <> ''
      when 'school_in' then btrim(school_name) <> ''
      when 'outgoing' then btrim(recipient) <> ''
      when 'school_received' then btrim(sender) <> ''
      else false
    end
  );

create index if not exists ped_correspondence_office_school_date_idx
  on public.ped_correspondence (office_id, school_id, correspondence_date desc)
  where category = 'school_in';
create index if not exists ped_correspondence_school_category_date_idx
  on public.ped_correspondence (school_id, category, correspondence_date desc);

-- Existing office registrations are linked only when the school account name
-- matches exactly and the school has been assigned to that same office.
update public.ped_correspondence as letter
   set school_id = school.id, office_id = letter.owner_id
  from public.profiles as school
 where letter.category = 'school_in'
   and letter.school_id is null
   and school.role = 'agency'
   and lower(btrim(school.agency_type)) = 'sekolah'
   and school.ped_office_id = letter.owner_id
   and lower(btrim(school.name)) = lower(btrim(letter.school_name));

create or replace function public.ped_school_office_id()
returns uuid language sql stable security definer set search_path = '' as $$
  select ped_office_id from public.profiles
   where id = (select auth.uid()) and role = 'agency'
     and lower(btrim(agency_type)) = 'sekolah';
$$;

create or replace function public.ped_is_office()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.profiles
     where id = (select auth.uid()) and role = 'agency'
       and lower(btrim(agency_type)) = 'pejabat'
  );
$$;

create or replace function public.ped_is_school()
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.profiles
     where id = (select auth.uid()) and role = 'agency'
       and lower(btrim(agency_type)) = 'sekolah'
  );
$$;

create or replace function public.ped_school_belongs_to_office(p_school_id uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.profiles
     where id = p_school_id and role = 'agency'
       and lower(btrim(agency_type)) = 'sekolah'
       and ped_office_id = (select auth.uid())
  );
$$;

-- School users may read their own profile and their assigned office name.
drop policy if exists profiles_ped_assigned_office_select on public.profiles;
create policy profiles_ped_assigned_office_select
on public.profiles for select to authenticated
using (id = (select public.ped_school_office_id()));

-- Assigned offices can list their schools for the incoming school form.
drop policy if exists profiles_ped_office_schools_select on public.profiles;
create policy profiles_ped_office_schools_select
on public.profiles for select to authenticated
using (ped_office_id = (select auth.uid()) and (select public.ped_is_office()));

-- The existing profile update grant is only for name and agency_type.
grant update (ped_office_id) on public.profiles to authenticated;

create or replace function public.ped_guard_office_assignment()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.agency_type is distinct from old.agency_type and not public.is_admin() then
    raise exception 'Hanya admin sistem boleh mengubah jenis agensi.' using errcode = '42501';
  end if;
  if new.ped_office_id is distinct from old.ped_office_id then
    if not public.is_admin() then
      raise exception 'Hanya admin sistem boleh menetapkan Pejabat sekolah.' using errcode = '42501';
    end if;
    if lower(btrim(new.agency_type)) <> 'sekolah' or new.role <> 'agency' then
      raise exception 'Pejabat PeD hanya boleh ditetapkan kepada akaun sekolah.' using errcode = '23514';
    end if;
    if new.ped_office_id is not null and not exists (
      select 1 from public.profiles p where p.id = new.ped_office_id
        and p.role = 'agency' and lower(btrim(p.agency_type)) = 'pejabat'
    ) then
      raise exception 'Pilih akaun Pejabat yang sah.' using errcode = '23514';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists ped_guard_office_assignment on public.profiles;
create trigger ped_guard_office_assignment
before update on public.profiles
for each row execute function public.ped_guard_office_assignment();

create or replace function public.ped_sync_school_office()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.ped_office_id is distinct from old.ped_office_id then
    update public.ped_correspondence
       set office_id = new.ped_office_id
     where owner_id = new.id and school_id = new.id and category = 'school_in';
    if new.ped_office_id is not null then
      update public.ped_correspondence
         set school_id = new.id, office_id = new.ped_office_id
       where owner_id = new.ped_office_id and category = 'school_in'
         and school_id is null
         and lower(btrim(school_name)) = lower(btrim(new.name));
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists ped_sync_school_office on public.profiles;
create trigger ped_sync_school_office
after update of ped_office_id on public.profiles
for each row execute function public.ped_sync_school_office();

create or replace function public.ped_validate_school_record()
returns trigger language plpgsql security definer set search_path = '' as $$
declare actor public.profiles;
declare target_school public.profiles;
begin
  select * into actor from public.profiles where id = auth.uid();
  if actor.role = 'admin' then
    return new;
  end if;
  if actor.role <> 'agency' then
    raise exception 'Akses PeD tidak dibenarkan.' using errcode = '42501';
  end if;

  if tg_op = 'UPDATE' and (new.owner_id <> old.owner_id or new.category <> old.category) then
    raise exception 'Pemilik atau kategori surat tidak boleh diubah.' using errcode = '42501';
  end if;

  if lower(btrim(actor.agency_type)) = 'sekolah' then
    if new.owner_id <> actor.id or new.category not in ('school_in', 'school_received') then
      raise exception 'Sekolah hanya boleh mengurus suratnya sendiri.' using errcode = '42501';
    end if;
    if new.category = 'school_in' then
      if actor.ped_office_id is null then
        raise exception 'Pejabat penerima belum ditetapkan untuk sekolah ini.' using errcode = '23514';
      end if;
      if tg_op = 'UPDATE' and old.status not in ('Dihantar', 'Dihantar Semula', 'Dikembalikan') then
        raise exception 'Surat yang sedang diproses Pejabat tidak boleh diubah oleh sekolah.' using errcode = '42501';
      end if;
      if new.status not in ('Dihantar', 'Dihantar Semula') then
        raise exception 'Status ini hanya boleh ditetapkan oleh Pejabat.' using errcode = '42501';
      end if;
      if tg_op = 'INSERT' and new.status <> 'Dihantar' then
        raise exception 'Surat Keluar baharu mesti berstatus Dihantar.' using errcode = '23514';
      end if;
      if tg_op = 'UPDATE' and old.status = 'Dihantar' and new.status <> 'Dihantar' then
        raise exception 'Surat hanya boleh dihantar semula selepas dikembalikan Pejabat.' using errcode = '23514';
      end if;
      if tg_op = 'UPDATE' and old.status = 'Dikembalikan'
         and new.status <> 'Dihantar Semula' then
        raise exception 'Surat yang dikembalikan mesti dihantar semula.' using errcode = '23514';
      end if;
      if tg_op = 'UPDATE' and
        (new.sender, new.recipient, new.department_sectors, new.assigned_officers,
         new.school_sector, new.assigned_to, new.office_reference_file,
         new.registry_file_number, new.origin_sector, new.delivery_methods,
         new.notes, new.attachment_path)
        is distinct from
        (old.sender, old.recipient, old.department_sectors, old.assigned_officers,
         old.school_sector, old.assigned_to, old.office_reference_file,
         old.registry_file_number, old.origin_sector, old.delivery_methods,
         old.notes, old.attachment_path) then
        raise exception 'Medan tindakan Pejabat tidak boleh diubah oleh sekolah.' using errcode = '42501';
      end if;
      new.school_id := actor.id;
      new.office_id := actor.ped_office_id;
      new.school_name := actor.name;
      new.correspondent := actor.name;
    else
      new.school_id := actor.id;
      new.office_id := null;
    end if;
  elsif new.category = 'school_received' then
    raise exception 'Surat Masuk Sekolah hanya untuk akaun sekolah.' using errcode = '42501';
  elsif new.category = 'school_in' and new.school_id is not null then
    select * into target_school from public.profiles where id = new.school_id;
    if lower(btrim(actor.agency_type)) <> 'pejabat'
       or target_school.ped_office_id is distinct from actor.id then
      raise exception 'Sekolah ini tidak ditetapkan kepada Pejabat anda.' using errcode = '42501';
    end if;
    if new.status = 'Dihantar Semula'
       and (tg_op = 'INSERT' or old.status is distinct from new.status) then
      raise exception 'Status Dihantar Semula hanya boleh ditetapkan oleh sekolah.' using errcode = '42501';
    end if;
    if tg_op = 'UPDATE' and old.owner_id <> actor.id
       and (new.correspondence_date, new.reference_number, new.correspondent,
            new.sender, new.school_name, new.recipient, new.department_sectors,
            new.assigned_officers, new.office_reference_file, new.origin_sector,
            new.delivery_methods, new.subject, new.attachment_path,
            new.school_id, new.office_id)
         is distinct from
           (old.correspondence_date, old.reference_number, old.correspondent,
            old.sender, old.school_name, old.recipient, old.department_sectors,
            old.assigned_officers, old.office_reference_file, old.origin_sector,
            old.delivery_methods, old.subject, old.attachment_path,
            old.school_id, old.office_id) then
      raise exception 'Butiran asal sekolah tidak boleh diubah oleh Pejabat.' using errcode = '42501';
    end if;
    new.office_id := actor.id;
    new.school_name := target_school.name;
    new.correspondent := target_school.name;
  end if;
  return new;
end;
$$;

drop trigger if exists ped_validate_school_record on public.ped_correspondence;
create trigger ped_validate_school_record
before insert or update on public.ped_correspondence
for each row execute function public.ped_validate_school_record();

drop policy if exists ped_correspondence_select on public.ped_correspondence;
create policy ped_correspondence_select on public.ped_correspondence
for select to authenticated using (
  (select public.can_access_ped())
  and (not (select public.ped_is_school()) or category in ('school_in', 'school_received'))
  and (
    ((select public.is_admin()) and category <> 'school_received') or owner_id = (select auth.uid())
    or (category = 'school_in' and school_id = (select auth.uid()))
    or (category = 'school_in' and office_id = (select auth.uid()) and (select public.ped_is_office()))
  )
);

drop policy if exists ped_correspondence_insert on public.ped_correspondence;
create policy ped_correspondence_insert on public.ped_correspondence
for insert to authenticated with check (
  (select public.can_access_ped()) and owner_id = (select auth.uid())
  and (
    ((select public.ped_is_school()) and category = 'school_in'
      and school_id = (select auth.uid()) and office_id = (select public.ped_school_office_id()))
    or (not (select public.ped_is_school()) and category <> 'school_received'
      and (category <> 'school_in' or school_id is null or
        ((select public.ped_is_office()) and (select public.ped_school_belongs_to_office(school_id)))))
    or (category = 'school_received' and school_id = (select auth.uid())
      and exists (select 1 from public.profiles p where p.id = (select auth.uid())
        and p.role = 'agency' and lower(btrim(p.agency_type)) = 'sekolah'))
  )
);

drop policy if exists ped_correspondence_update on public.ped_correspondence;
create policy ped_correspondence_update on public.ped_correspondence
for update to authenticated
using (
  (select public.can_access_ped())
  and (not (select public.ped_is_school()) or category in ('school_in', 'school_received'))
  and (
    ((select public.is_admin()) and category <> 'school_received') or owner_id = (select auth.uid())
    or (category = 'school_in' and office_id = (select auth.uid()) and (select public.ped_is_office()))
  )
)
with check (
  (select public.can_access_ped())
  and (not (select public.ped_is_school()) or category in ('school_in', 'school_received'))
  and (
    ((select public.is_admin()) and category <> 'school_received') or owner_id = (select auth.uid())
    or (category = 'school_in' and office_id = (select auth.uid()) and (select public.ped_is_office()))
  )
);

drop policy if exists ped_correspondence_delete on public.ped_correspondence;
create policy ped_correspondence_delete on public.ped_correspondence
for delete to authenticated using (
  (select public.can_access_ped())
  and (not (select public.ped_is_school()) or category in ('school_in', 'school_received'))
  and (((select public.is_admin()) and category <> 'school_received') or (
    owner_id = (select auth.uid()) and
    (category <> 'school_in' or not (select public.ped_is_school())
      or status in ('Dihantar', 'Dihantar Semula', 'Dikembalikan'))
  ))
);

grant update (school_id, office_id) on public.ped_correspondence to authenticated;

-- Existing access to the attachment bucket remains scoped to the uploader.
revoke all on function public.ped_school_office_id() from public;
revoke all on function public.ped_is_office() from public;
revoke all on function public.ped_is_school() from public;
revoke all on function public.ped_school_belongs_to_office(uuid) from public;
grant execute on function public.ped_school_office_id() to authenticated;
grant execute on function public.ped_is_office() to authenticated;
grant execute on function public.ped_is_school() to authenticated;
grant execute on function public.ped_school_belongs_to_office(uuid) to authenticated;

notify pgrst, 'reload schema';
commit;
